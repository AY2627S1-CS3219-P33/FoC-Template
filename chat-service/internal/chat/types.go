// Package chat holds chat-service's business types and, from phase 3, its
// rules (who may read or send, and the room lifecycle). REST, WebSocket and
// the event consumer all go through it, so their rules cannot drift apart.
//
// It must not import httpapi, ws or store: store converts database rows into
// these types, never the other way round.
package chat

import (
	"errors"
	"time"

	"github.com/google/uuid"
)

// Status is a room's state. It is calculated from ClosesAt and the current
// time, never stored, so every copy of the service agrees without a
// background job.
type Status string

const (
	// StatusOpen: the errand has not ended for this room.
	StatusOpen Status = "OPEN"
	// StatusClosing: the errand ended, but the room is writable until ClosesAt.
	StatusClosing Status = "CLOSING"
	// StatusClosed: read-only.
	StatusClosed Status = "CLOSED"
)

// EndReason says why the errand ended for a room.
type EndReason string

const (
	// EndWithdrawn ends only the withdrawing courier's room.
	EndWithdrawn EndReason = "WITHDRAWN"
	// EndCompleted and EndRefunded end every room of the errand.
	EndCompleted EndReason = "COMPLETED"
	EndRefunded  EndReason = "REFUNDED"
)

// Role is a participant's side of a room.
type Role string

const (
	RoleRequester Role = "REQUESTER"
	RoleCourier   Role = "COURIER"
)

// Room connects an errand's requester with one courier who accepted it. A
// room belongs to one (ErrandID, CourierID) pair; a later courier gets a new
// room.
type Room struct {
	ID          uuid.UUID
	ErrandID    uuid.UUID
	RequesterID string // Auth0 subject
	CourierID   string // Auth0 subject
	// OpenedVersion is the errandVersion of errand.accepted; nil while
	// errand.withdrawn has arrived before it.
	OpenedVersion *int
	// Ending is nil while the errand has not ended for this room.
	Ending    *Ending
	CreatedAt time.Time
}

// Ending is when and why the errand ended for a room, and when the room
// becomes read-only.
type Ending struct {
	Reason   EndReason
	EndedAt  time.Time // the event's occurredAt
	ClosesAt time.Time // EndedAt + CHAT_CLOSE_DELAY
}

// Status reports the room's state at now.
func (r Room) Status(now time.Time) Status {
	switch {
	case r.Ending == nil:
		return StatusOpen
	case now.Before(r.Ending.ClosesAt):
		return StatusClosing
	default:
		return StatusClosed
	}
}

// RoleOf reports userID's side of the room, and false for an outsider.
func (r Room) RoleOf(userID string) (Role, bool) {
	if userID == "" {
		return "", false
	}
	switch userID {
	case r.RequesterID:
		return RoleRequester, true
	case r.CourierID:
		return RoleCourier, true
	}
	return "", false
}

// RoomSummary is a room in a list, with its newest message (nil if none).
type RoomSummary struct {
	Room        Room
	LastMessage *Message
}

// Message is one chat message. IDs increase, so they order messages and page
// through them.
type Message struct {
	ID       int64
	RoomID   uuid.UUID
	SenderID string
	Body     string
	// ClientMsgID is generated by the browser per message; a retried send
	// with the same ID stores nothing new.
	ClientMsgID string
	CreatedAt   time.Time
}

// AcceptedRoom is the room errand.accepted asks for.
type AcceptedRoom struct {
	ErrandID      uuid.UUID
	RequesterID   string
	CourierID     string
	OpenedVersion int // errandVersion of errand.accepted
}

// NewMessage is a message to store. Service.Send checks the rules first; the
// database only backs up the length rules.
type NewMessage struct {
	RoomID      uuid.UUID
	SenderID    string
	Body        string
	ClientMsgID string
}

// ErrandEnding records that a whole errand completed or was refunded.
type ErrandEnding struct {
	ErrandID uuid.UUID
	Reason   EndReason // EndCompleted or EndRefunded
	EndedAt  time.Time
}

// Errors that callers can act on. The store returns these instead of raw
// database errors.
var (
	// ErrRoomNotFound: no such room. Phase 3 also returns it to outsiders, so
	// they cannot tell whether a room exists.
	ErrRoomNotFound = errors.New("room not found")
	// ErrInvalidMessage: the message breaks a rule (body length, client
	// message ID length).
	ErrInvalidMessage = errors.New("invalid message")
	// ErrRoomClosed: the room is read-only, so sending is refused.
	ErrRoomClosed = errors.New("room is closed")
	// ErrInvalidPage: the paging parameters are wrong (both after and
	// before, a negative ID, or a limit out of range).
	ErrInvalidPage = errors.New("invalid page")
	// ErrInvalidRoom: room data breaks a rule, for example the requester and
	// the courier are the same person, or an unknown end reason.
	ErrInvalidRoom = errors.New("invalid room data")
	// ErrUnavailable: the database failed. Retrying later may work, so the
	// event consumer requeues the event.
	ErrUnavailable = errors.New("storage unavailable")
)
